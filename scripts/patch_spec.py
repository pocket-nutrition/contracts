"""Produce openapi.patched.json from openapi.upstream.json + overlay.yaml.

The upstream document is generated by springdoc from Kotlin annotations and is not directly
usable for client generation:

  * It carries no `required` arrays at all, so every generated field is optional in both Kotlin
    and Swift — including energyKcal and ingredientId. That is not a domain type, it is a bag of
    maybes, and it pushes a `?: 0.0` decision to every call site in two languages.
  * It does not document the X-Segment-Count response header, so no generator emits an accessor,
    and multi-select search (spec §7.1) silently disappears.
  * /health is @Hidden and therefore absent, although the apps need it to validate a
    user-entered server address.
  * Its enums are closed, and a shipped mobile binary cannot learn a new value.

This script fixes all four. Run it after refreshing the upstream snapshot:

    python3 scripts/patch_spec.py            # write openapi.patched.json
    python3 scripts/patch_spec.py --check    # exit 1 if the committed output is stale (CI)

Output is byte-reproducible: no timestamps, no environment-dependent values. That is what makes
--check trustworthy.

Requires PyYAML, and nothing else by design — this repo has no build.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "openapi" / "openapi.upstream.json"
OVERLAY = ROOT / "openapi" / "overlay.yaml"
PATCHED = ROOT / "openapi" / "openapi.patched.json"
VERSION_FILE = ROOT / "VERSION"


def is_nullable(prop: dict[str, Any]) -> bool:
    """Whether a property schema admits null, in either encoding springdoc uses.

    springdoc expresses nullability as:
      scalars / arrays / objects   {"type": ["number", "null"]}
      $ref properties              {"oneOf": [{"$ref": "..."}, {"type": "null"}]}

    A bare $ref (no oneOf/anyOf wrapper) carries no nullability information whatsoever. We treat
    it as non-nullable, which is correct for every such property in contract 1.1.0
    (RecipeComponentResponse.ingredient is the only one). If that ever stops being true, the
    offending property must be listed under requiredOverrides.<schema>.exclude in overlay.yaml,
    or the generated model is non-optional and the first null response crashes decoding.
    """
    declared = prop.get("type")
    if isinstance(declared, list):
        return "null" in declared
    if declared == "null":
        return True

    for key in ("oneOf", "anyOf"):
        for variant in prop.get(key, []):
            variant_type = variant.get("type")
            if variant_type == "null" or (
                isinstance(variant_type, list) and "null" in variant_type
            ):
                return True
    return False


def derive_required(schema: dict[str, Any]) -> list[str]:
    """Required = every property that does not admit null.

    This mirrors Kotlin nullability exactly, which is the real source of truth: `val x: Double` is
    always serialised, `val x: Double?` may be absent. Deriving rather than hand-listing means a
    newly added DTO field is classified automatically, instead of silently defaulting to optional
    because nobody updated a list living in another repository.

    Declaration order is preserved (not sorted) so diffs stay readable when a field is inserted.
    """
    return [
        name for name, prop in schema.get("properties", {}).items() if not is_nullable(prop)
    ]


def normalize_nullable_refs(doc: dict[str, Any]) -> list[str]:
    """Rewrite `oneOf: [{$ref}, {type: null}]` to a bare `$ref`.

    THIS IS NOT COSMETIC. Verified against swift-openapi-generator 1.13.0 and
    openapi-generator 7.24.0 on contract 1.1.0:

      * openapi-generator (Kotlin) understands the oneOf-with-null form and emits
        `val nutrition: NutritionalProfileResponse? = null`.
      * swift-openapi-generator does NOT. It logs
            warning: Schema "null" is not supported, reason: "schema type", skipping
        and then **omits the property from the generated struct altogether** — the build still
        succeeds. IngredientSuggestionWithNutrition came out with 16 properties in Swift versus
        17 in Kotlin, the missing one being `nutrition`: the entire nutritional payload of an
        enriched search result. Nothing would have failed at runtime; the data would simply never
        have existed on iOS.

    Optionality is preserved because it is carried by the `required` array instead, which both
    generators honour. Call this AFTER apply_required(), so nullability is still visible when
    required is derived.

    If a future generator regresses on bare-$ref optionality, the parity check that compares
    property counts across the two generated clients is what catches it — not this function.
    """
    log: list[str] = []

    def rewrite(container: dict[str, Any], where: str) -> None:
        for prop_name, prop in list(container.items()):
            if not isinstance(prop, dict):
                continue
            variants = prop.get("oneOf")
            if not isinstance(variants, list) or len(variants) != 2:
                continue

            ref_variants = [v for v in variants if isinstance(v, dict) and "$ref" in v]
            null_variants = [v for v in variants if isinstance(v, dict) and v.get("type") == "null"]
            if len(ref_variants) != 1 or len(null_variants) != 1:
                continue

            replacement = {"$ref": ref_variants[0]["$ref"]}
            # Preserve any sibling annotations the upstream document carried.
            for key, value in prop.items():
                if key != "oneOf":
                    replacement[key] = value
            container[prop_name] = replacement
            log.append(f"  {where}.{prop_name}: oneOf[$ref,null] -> bare $ref")

    for schema_name, schema in doc.get("components", {}).get("schemas", {}).items():
        if isinstance(schema.get("properties"), dict):
            rewrite(schema["properties"], schema_name)

    return log


def deep_merge(base: Any, patch: Any) -> Any:
    """Recursively merge `patch` into `base`, returning a new structure.

    Dicts merge key-wise. Everything else — including lists — is replaced outright: element-wise
    list merging has no unambiguous semantics, and silently reordering an OpenAPI array would be
    worse than an explicit overwrite.
    """
    if isinstance(base, dict) and isinstance(patch, dict):
        merged = dict(base)
        for key, patch_value in patch.items():
            merged[key] = deep_merge(base[key], patch_value) if key in base else patch_value
        return merged
    return patch


def apply_required(doc: dict[str, Any], overrides: dict[str, Any]) -> list[str]:
    log: list[str] = []
    schemas = doc.get("components", {}).get("schemas", {})

    for name, schema in schemas.items():
        if "properties" not in schema:
            continue
        if "required" in schema:
            log.append(f"  {name}: upstream already declares required — left untouched")
            continue

        required = derive_required(schema)
        override = overrides.get(name) or {}

        for excluded in override.get("exclude", []):
            if excluded not in required:
                raise SystemExit(
                    f"overlay.yaml: requiredOverrides.{name}.exclude lists '{excluded}', which is "
                    f"not in the derived required set. Remove the stale entry."
                )
            required.remove(excluded)
            log.append(f"  {name}: excluded '{excluded}' per overlay")

        for included in override.get("include", []):
            if included not in schema["properties"]:
                raise SystemExit(
                    f"overlay.yaml: requiredOverrides.{name}.include lists '{included}', which is "
                    f"not a property of {name}."
                )
            if included not in required:
                required.append(included)
                log.append(f"  {name}: forced '{included}' required per overlay")

        # Always set `required`, even when empty: an all-nullable schema (e.g. a reference-data
        # DTO whose fields are all "unknown when unavailable") must say so explicitly, or a
        # generator that defaults a missing `required` key to "everything required" would emit a
        # non-optional field the server can legitimately omit — the exact failure mode this
        # derivation exists to prevent for every other schema.
        schema["required"] = required
        log.append(f"  {name}: {len(required)}/{len(schema['properties'])} required")

    return log


def apply_extensible_enums(doc: dict[str, Any], entries: list[dict[str, str]]) -> list[str]:
    log: list[str] = []
    schemas = doc.get("components", {}).get("schemas", {})

    for entry in entries:
        schema_name, prop_name = entry["schema"], entry["property"]
        schema = schemas.get(schema_name)
        if schema is None:
            raise SystemExit(
                f"overlay.yaml: extensibleEnums references unknown schema {schema_name}"
            )

        prop = schema.get("properties", {}).get(prop_name)
        if prop is None:
            raise SystemExit(
                f"overlay.yaml: extensibleEnums references unknown property "
                f"{schema_name}.{prop_name}"
            )
        if "enum" not in prop:
            raise SystemExit(
                f"overlay.yaml: {schema_name}.{prop_name} has no enum in the upstream document. "
                f"Either the API dropped its allowableValues annotation, or this entry is stale."
            )

        prop["x-extensible-enum"] = prop["enum"]
        log.append(f"  {schema_name}.{prop_name}: {len(prop['enum'])} values, extensible")

    return log


def build() -> tuple[str, list[str]]:
    doc = json.loads(UPSTREAM.read_text())
    overlay = yaml.safe_load(OVERLAY.read_text()) or {}

    meta = overlay.get("meta") or {}
    upstream_version = doc.get("info", {}).get("version")
    expected = meta.get("appliesToContractVersion")
    log: list[str] = []

    if expected and expected != upstream_version:
        log.append(
            f"  WARNING: overlay targets contract {expected} but the snapshot is "
            f"{upstream_version}. Re-read overlay.yaml before trusting this output."
        )

    log.append("required (derived from nullability):")
    log += apply_required(doc, overlay.get("requiredOverrides") or {})

    # Must run AFTER apply_required: the oneOf-with-null form is what makes these properties
    # detectably nullable, and we need that signal before flattening it away.
    log.append("nullable $ref normalization (swift-openapi-generator drops oneOf-with-null):")
    log += normalize_nullable_refs(doc)

    log.append("extensible enums:")
    log += apply_extensible_enums(doc, overlay.get("extensibleEnums") or [])

    patch = overlay.get("patch") or {}
    doc = deep_merge(doc, patch)
    log.append(f"structural patch: merged {len(patch.get('paths') or {})} path entries")

    # Provenance, so a generated client can be traced back to its inputs. Deliberately contains no
    # timestamp: --check compares bytes, and a clock would make it fail spuriously.
    doc["x-pn-overlay"] = {
        "contractsVersion": VERSION_FILE.read_text().strip(),
        "overlayVersion": meta.get("overlayVersion"),
        "upstreamContractVersion": upstream_version,
        "generatedBy": "scripts/patch_spec.py",
        "note": "Generated file. Edit overlay.yaml and re-run; never edit this document.",
    }

    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n", log


def main() -> int:
    parser = argparse.ArgumentParser(description="Apply overlay.yaml to the upstream OpenAPI spec.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed openapi.patched.json is stale (for CI)",
    )
    args = parser.parse_args()

    output, log = build()
    relative = PATCHED.relative_to(ROOT)

    if args.check:
        if not PATCHED.exists():
            print(f"FAIL: {relative} does not exist. Run: python3 scripts/patch_spec.py")
            return 1
        if PATCHED.read_text() != output:
            print(
                f"FAIL: {relative} is stale.\n"
                f"      Run: python3 scripts/patch_spec.py   then commit the result."
            )
            return 1
        print(f"OK: {relative} is up to date")
        return 0

    PATCHED.write_text(output)
    print("\n".join(log))
    print(f"\nwrote {relative} ({len(output)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
